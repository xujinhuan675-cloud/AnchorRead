import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import webpackPackage from 'next/dist/compiled/webpack/webpack.js';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const output = join(root, 'lib/diagram-mcp-app-bootstrap-source.js');
const temp = mkdtempSync(join(tmpdir(), 'anchorread-mcp-app-'));
const compiler = webpackPackage.webpack({
  mode: 'production',
  context: root,
  entry: './lib/diagram-mcp-app-bootstrap.js',
  target: ['web', 'es2020'],
  devtool: false,
  optimization: { minimize: false },
  output: { path: temp, filename: 'bootstrap.js' },
});

try {
  await new Promise((resolve, reject) => compiler.run((error, stats) => {
    if (error || stats?.hasErrors()) reject(error || new Error(stats.toString({ all: false, errors: true })));
    else resolve();
  }));
  const sdkUrl = import.meta.resolve('@modelcontextprotocol/ext-apps/app-with-deps');
  const sdkRequire = createRequire(sdkUrl);
  const license = readFileSync(new URL('../../LICENSE', sdkUrl), 'utf8')
    + '\n' + readFileSync(join(dirname(sdkRequire.resolve('zod/package.json')), 'LICENSE'), 'utf8');
  const source = '/* @modelcontextprotocol/ext-apps 0.4.0 (bundled MCP SDK and Zod)\n' + license + '\n*/\n'
    + readFileSync(join(temp, 'bootstrap.js'), 'utf8');
  const generated = '// Generated by npm run build:mcp-app; do not edit.\nconst bootstrapSource = '
    + JSON.stringify(source.replace(/<\/script/giu, '<\\/script')) + ';\nexport default bootstrapSource;\n';
  if (process.argv.includes('--check')) assert.equal(readFileSync(output, 'utf8'), generated, 'MCP App bootstrap is stale');
  else writeFileSync(output, generated);
  console.log('MCP App bootstrap: ' + Buffer.byteLength(source) + ' bytes, no external startup imports');
} finally {
  await new Promise((resolve, reject) => compiler.close((error) => error ? reject(error) : resolve()));
  rmSync(temp, { recursive: true, force: true });
}
